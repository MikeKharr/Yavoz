import unittest

from yavoz.rank import (ВЫСОКАЯ, НИЗКАЯ, СРЕДНЯЯ, Персона, главная_страница,
                        достал_текст, заголовок_страницы, значимые, нормализовать,
                        оценить_адрес, оценить_текст, уверенность)

ПЕРСОНА = Персона("Беспалов", "Дмитрий", "Викторович",
                  "Курский государственный университет",
                  "Декан факультета физической культуры и спорта")


class Нормализация(unittest.TestCase):
    def test_ё_и_е_не_различаются(self):
        self.assertEqual(нормализовать("Актёр"), нормализовать("Актер"))

    def test_служебные_слова_не_идут_в_значимые(self):
        self.assertNotIn("кафедры", значимые("Ассистент кафедры права"))
        self.assertIn("ассистент", значимые("Ассистент кафедры права"))


class ОценкаАдреса(unittest.TestCase):
    def test_государственный_домен_весомее_обычного(self):
        гос = оценить_адрес("https://shkola-r71.gosweb.gosuslugi.ru/x")
        обычный = оценить_адрес("https://example.ru/x")
        self.assertGreater(гос.балл, обычный.балл)

    def test_соцсеть_уходит_в_минус(self):
        self.assertLess(оценить_адрес("https://vk.ru/wall-1_2").балл, 0)

    def test_раздел_о_сотрудниках_добавляет_вес(self):
        со = оценить_адрес("https://kursksu.ru/people/view/316")
        без = оценить_адрес("https://kursksu.ru/news/2024")
        self.assertGreater(со.балл, без.балл)

    def test_агрегатор_и_новости_не_считаются_подтверждением(self):
        self.assertLess(оценить_адрес("https://hh.ru/employer/1").балл, 0)
        self.assertLess(оценить_адрес("https://ria.ru/2024/text.html").балл,
                        оценить_адрес("https://example.ru/2024/text.html").балл)


class ОценкаТекста(unittest.TestCase):
    def test_страница_без_фамилии_не_получает_за_фио(self):
        о = оценить_текст("Факультет физической культуры и спорта", ПЕРСОНА)
        self.assertNotIn("фамилия и имя на странице", " ".join(о.доводы))

    def test_однофамилец_с_другим_именем_уходит_в_минус(self):
        # Настоящий случай: на «Мичурина Алексея» выпала статья про «Мичурина Василия».
        мичурин = Персона("Мичурин", "Алексей", "Николаевич", "СПбГУ", "Профессор")
        о = оценить_текст("Мичурин, Василий Сергеевич — советский лётчик", мичурин,
                          "Мичурин, Василий Сергеевич")
        self.assertIn("вероятно однофамилец", " ".join(о.доводы))
        self.assertLess(о.балл, 0)
        self.assertEqual(уверенность(о.балл, о.доводы), НИЗКАЯ)

    def test_совпадение_фамилии_и_имени_весомее_одной_фамилии(self):
        оба = оценить_текст("Беспалов Дмитрий Викторович, декан факультета "
                            "физической культуры и спорта", ПЕРСОНА)
        одна = оценить_текст("Беспалов, декан факультета физической культуры", ПЕРСОНА)
        self.assertGreater(оба.балл, одна.балл)

    def test_главная_страница_не_подтверждает_человека(self):
        текст = "Бессонова Татьяна Николаевна воспитатель"
        глубокая = оценить_текст(текст, ПЕРСОНА, url="https://shkola.ru/staff/ivanov")
        главная = оценить_текст(текст, ПЕРСОНА, url="https://shkola.ru/")
        self.assertGreater(глубокая.балл, главная.балл)
        self.assertIn("главная страница", " ".join(главная.доводы))

    def test_односложная_должность_даёт_меньше_чем_многословная(self):
        один = Персона("Иванов", "Иван", "", "Школа 1", "Воспитатель")
        много = Персона("Иванов", "Иван", "", "Школа 1", "Декан факультета спорта")
        о1 = оценить_текст("Иванов Иван воспитатель", один)
        о2 = оценить_текст("Иванов Иван декан факультета спорта", много)
        self.assertLess(о1.балл, о2.балл)

    def test_должность_на_странице_весомее_её_отсутствия(self):
        с_должностью = оценить_текст(
            "Беспалов Дмитрий Викторович, декан факультета физической культуры и спорта",
            ПЕРСОНА)
        без = оценить_текст("Беспалов Дмитрий Викторович", ПЕРСОНА)
        self.assertGreater(с_должностью.балл, без.балл)

    def test_однофамилец_без_должности_не_даёт_высокой_уверенности(self):
        о = оценить_текст("Беспалов выступил на концерте", ПЕРСОНА)
        self.assertNotEqual(уверенность(о.балл, о.доводы), ВЫСОКАЯ)


class Уверенность(unittest.TestCase):
    def test_официальный_плюс_фио_плюс_должность_дают_высокую(self):
        доводы = ["+40 государственный домен", "+20 фамилия и имя на странице",
                  "+25 должность на странице (4 из 6)"]
        self.assertEqual(уверенность(85, доводы), ВЫСОКАЯ)

    def test_соцсеть_с_фамилией_остаётся_низкой(self):
        self.assertEqual(
            уверенность(-10, ["-30 соцсеть", "+20 фамилия и имя на странице"]), НИЗКАЯ)

    def test_агрегатор_не_даёт_высокой_даже_при_большом_балле(self):
        # Настоящий случай: rusprofile получал «высокую», набрав баллы на всём прочем.
        доводы = ["-25 агрегатор или справочник", "+20 фамилия и имя на странице",
                  "+10 отчество на странице", "+10 фамилия в заголовке",
                  "+25 должность на странице (1 из 2)", "+12 организация на странице",
                  "+25 раздел о сотрудниках или структуре"]
        self.assertNotEqual(уверенность(100, доводы), ВЫСОКАЯ)

    def test_соцсеть_с_полным_фио_и_должностью_не_выше_средней(self):
        доводы = ["-30 соцсеть", "+20 фамилия и имя на странице",
                  "+25 должность на странице (2 из 4)", "+12 организация на странице"]
        self.assertEqual(уверенность(45, доводы), СРЕДНЯЯ)

    def test_главная_страница_не_даёт_высокой(self):
        доводы = ["+40 государственный домен", "+20 фамилия и имя на странице",
                  "+25 должность на странице (2 из 2)",
                  "-25 главная страница, а не карточка человека"]
        self.assertNotEqual(уверенность(80, доводы), ВЫСОКАЯ)


class ГлавнаяСтраница(unittest.TestCase):
    def test_корень_и_индексы_считаются_главной(self):
        for url in ("https://x.ru", "https://x.ru/", "https://x.ru/index.html"):
            self.assertTrue(главная_страница(url), url)

    def test_страница_с_путём_главной_не_считается(self):
        self.assertFalse(главная_страница("https://x.ru/sveden/staff"))


class ИзвлечениеТекста(unittest.TestCase):
    def test_скрипты_и_стили_не_попадают_в_текст(self):
        h = "<html><head><style>.a{color:red}</style><script>var x=1</script>" \
            "<title>Карточка</title></head><body><p>Беспалов Д. В.</p></body></html>"
        текст = достал_текст(h)
        self.assertIn("Беспалов", текст)
        self.assertNotIn("color:red", текст)
        self.assertNotIn("var x", текст)
        self.assertEqual(заголовок_страницы(h), "Карточка")


if __name__ == "__main__":
    unittest.main()
