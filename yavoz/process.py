"""Обработка одного файла: поиск источника для каждой строки и запись U и V."""
from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Callable, Iterable

import requests

from . import preserve, xlsx
from .rank import (ВЫСОКАЯ, НИЗКАЯ, Оценка, Персона, загрузить, оценить_адрес,
                   оценить_текст, уверенность)
from .search import Hit, Search

# Сколько верхних кандидатов дочитываем со страницы. Остальные судим по выдаче:
# читать все десять на каждую строку — это тысячи загрузок на файл.
ЧИТАЕМ = 4


@dataclass
class Кандидат:
    url: str
    балл: int
    доводы: list[str]
    уверенность: str
    заголовок: str = ""


@dataclass
class ИтогСтроки:
    строка: int
    фио: str
    действие: str            # «заполнено», «пропущено», «не найдено», «ошибка»
    url: str = ""
    уверенность: str = ""
    доводы: list[str] = field(default_factory=list)
    примечание: str = ""


def пометка(уверен: str, доводы: Iterable[str]) -> str:
    return f"Yavoz: уверенность {уверен}. " + "; ".join(доводы)


def выбрать(персона: Персона, находки: list[Hit],
            читатель: Callable[[str], tuple[str, str]]) -> list[Кандидат]:
    """Ранжирует находки: сначала по адресу и сниппету, затем дочитывает верхние."""
    предварительно: list[tuple[int, Hit, Оценка]] = []
    for h in находки:
        о = оценить_адрес(h.url)
        по_сниппету = оценить_текст(f"{h.title} {h.snippet}", персона, h.title)
        предварительно.append((о.балл + по_сниппету.балл, h, о))
    предварительно.sort(key=lambda т: т[0], reverse=True)

    кандидаты: list[Кандидат] = []
    for место, (_, h, о_адрес) in enumerate(предварительно):
        if место < ЧИТАЕМ:
            текст, заголовок = читатель(h.url)
        else:
            текст, заголовок = f"{h.title} {h.snippet}", h.title
        о_текст = оценить_текст(текст, персона, заголовок or h.title)
        доводы = о_адрес.доводы + о_текст.доводы
        балл = о_адрес.балл + о_текст.балл
        кандидаты.append(Кандидат(url=h.url, балл=балл, доводы=доводы,
                                  уверенность=уверенность(балл, доводы),
                                  заголовок=заголовок or h.title))
    кандидаты.sort(key=lambda к: к.балл, reverse=True)
    return кандидаты


class Обработчик:
    def __init__(self, поиск: Search, session: requests.Session | None = None,
                 читатель: Callable[[str], tuple[str, str]] | None = None) -> None:
        self._поиск = поиск
        self._session = session or requests.Session()
        self._читатель = читатель or (lambda url: загрузить(url, self._session))

    def файл(self, источник: Path, цель: Path, предел: int = 0,
             событие: Callable[[dict], None] | None = None) -> list[ИтогСтроки]:
        сообщить = событие or (lambda _: None)
        книга = xlsx.открыть(источник)
        лист = xlsx.найти_лист(книга)
        строки = xlsx.строки(лист, предел)
        сообщить({"вид": "файл", "лист": лист.title, "строк": len(строки)})

        итоги: list[ИтогСтроки] = []
        for i, стр in enumerate(строки, 1):
            фио = " ".join(x for x in (стр.персона.фамилия, стр.персона.имя,
                                       стр.персона.отчество) if x)
            if стр.u_пуст:
                xlsx.записать_u(лист, стр.номер)
            if not стр.v_пуст:
                итог = ИтогСтроки(строка=стр.номер, фио=фио, действие="пропущено",
                                  примечание="V уже заполнен — не трогаем")
                итоги.append(итог)
                сообщить({"вид": "строка", "номер": i, "всего": len(строки), **asdict(итог)})
                continue
            try:
                находки = self._поиск.find(стр.персона.запрос())
                кандидаты = выбрать(стр.персона, находки, self._читатель)
            except Exception as err:  # сеть и API падают, строка не должна ронять файл
                итог = ИтогСтроки(строка=стр.номер, фио=фио, действие="ошибка",
                                  примечание=f"{type(err).__name__}: {err}"[:300])
                итоги.append(итог)
                сообщить({"вид": "строка", "номер": i, "всего": len(строки), **asdict(итог)})
                continue

            if не_пусто(кандидаты):
                лучший = кандидаты[0]
                xlsx.записать_v(лист, стр.номер, лучший.url,
                                пометка(лучший.уверенность, лучший.доводы))
                итог = ИтогСтроки(строка=стр.номер, фио=фио, действие="заполнено",
                                  url=лучший.url, уверенность=лучший.уверенность,
                                  доводы=лучший.доводы)
            else:
                итог = ИтогСтроки(строка=стр.номер, фио=фио, действие="не найдено",
                                  примечание="поиск ничего не вернул")
            итоги.append(итог)
            сообщить({"вид": "строка", "номер": i, "всего": len(строки), **asdict(итог)})

        xlsx.сохранить(книга, цель)
        перенесено = preserve.перенести_проверки(источник, цель)
        сообщить({"вид": "сохранено", "файл": цель.name, "проверки": перенесено})
        return итоги


def не_пусто(кандидаты: list[Кандидат]) -> bool:
    return bool(кандидаты)


def журнал(итоги: list[ИтогСтроки], файл: str) -> dict:
    счёт: dict[str, int] = {}
    для_уверенности: dict[str, int] = {}
    for и in итоги:
        счёт[и.действие] = счёт.get(и.действие, 0) + 1
        if и.уверенность:
            для_уверенности[и.уверенность] = для_уверенности.get(и.уверенность, 0) + 1
    return {"файл": файл, "время": time.strftime("%Y-%m-%d %H:%M:%S"),
            "итого": счёт, "уверенность": для_уверенности,
            "строки": [asdict(и) for и in итоги]}


def сохранить_журнал(данные: dict, путь: Path) -> Path:
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(json.dumps(данные, ensure_ascii=False, indent=2), encoding="utf-8")
    return путь
